// Helper to get relative ISO date strings (e.g. today, 10 days ago, etc.)
function getOffsetDate(daysOffset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  return d.toISOString().split('T')[0];
}

